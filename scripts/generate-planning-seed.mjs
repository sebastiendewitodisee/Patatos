import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { planningEvents } from "../src/data/planning.js";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, "..");

const FR_LOCALE_PATH = path.join(projectRoot, "src", "i18n", "locales", "fr.json");
const NL_LOCALE_PATH = path.join(projectRoot, "src", "i18n", "locales", "nl.json");
const OUTPUT_DIR = path.join(projectRoot, "supabase", "seeds");
const OUTPUT_PATH = path.join(OUTPUT_DIR, "planning_items_seed.sql");

const ALLOWED_PHASE_IDS = new Set(["preparation", "plantation", "suivi", "recolte", "conservation"]);
const ALLOWED_TYPES = new Set(["task", "preparation", "plantation", "suivi", "recolte", "conservation"]);
const ALLOWED_STATUSES = new Set(["todo", "doing", "done"]);

function getNested(obj, keyPath) {
  if (!obj || typeof obj !== "object") {
    return undefined;
  }

  if (typeof keyPath !== "string" || keyPath.trim().length === 0) {
    return undefined;
  }

  return keyPath.split(".").reduce((currentValue, keyPart) => {
    if (currentValue && typeof currentValue === "object" && Object.hasOwn(currentValue, keyPart)) {
      return currentValue[keyPart];
    }

    return undefined;
  }, obj);
}

function sqlEscape(value) {
  return String(value ?? "")
    .replace(/\r\n/g, "\n")
    .replace(/'/g, "''");
}

function normalizePhaseId(value) {
  const phaseId = String(value ?? "")
    .trim()
    .toLowerCase();

  if (ALLOWED_PHASE_IDS.has(phaseId)) {
    return phaseId;
  }

  return "preparation";
}

function normalizeType(value, fallbackPhaseId) {
  const normalizedValue = String(value ?? "")
    .trim()
    .toLowerCase();

  if (ALLOWED_TYPES.has(normalizedValue)) {
    return normalizedValue;
  }

  if (ALLOWED_TYPES.has(fallbackPhaseId)) {
    return fallbackPhaseId;
  }

  return "task";
}

function normalizeStatus(value) {
  const status = String(value ?? "")
    .trim()
    .toLowerCase();

  if (ALLOWED_STATUSES.has(status)) {
    return status;
  }

  return "todo";
}

function resolveLocalizedValue(localeJson, translationKey, fallbackValue) {
  const translatedValue = getNested(localeJson, translationKey);

  if (typeof translatedValue === "string" && translatedValue.trim().length > 0) {
    return translatedValue.trim();
  }

  if (typeof fallbackValue === "string") {
    return fallbackValue.trim();
  }

  return "";
}

function toInt(value, fallbackValue) {
  const parsedValue = Number(value);
  if (!Number.isFinite(parsedValue)) {
    return fallbackValue;
  }

  return Math.trunc(parsedValue);
}

function buildLanguageRows(localeJson, lang) {
  return planningEvents.map((event, index) => {
    const sortOrder = toInt(event?.order, index + 1);
    const phaseId = normalizePhaseId(event?.phaseId ?? event?.phase);
    const type = normalizeType(event?.type, phaseId);
    const status = normalizeStatus(event?.status);
    const title = resolveLocalizedValue(localeJson, event?.titleKey, event?.title);
    const description = resolveLocalizedValue(localeJson, event?.descriptionKey, event?.description);
    const period = resolveLocalizedValue(localeJson, event?.periodKey, event?.period ?? event?.date ?? "");

    return {
      lang,
      phaseId,
      type,
      title,
      description,
      period,
      status,
      sortOrder,
    };
  });
}

function toInsertValuesSql(rows) {
  return rows
    .map(
      (row) =>
        `  ('${row.lang}', '${row.phaseId}', '${row.type}', '${sqlEscape(row.title)}', '${sqlEscape(row.description)}', '${sqlEscape(row.period)}', '${row.status}', ${row.sortOrder})`
    )
    .join(",\n");
}

function buildSql(frRows, nlRows) {
  return [
    "-- Generated by scripts/generate-planning-seed.mjs",
    "-- Source: src/data/planning.js + src/i18n/locales/{fr,nl}.json",
    "",
    "BEGIN;",
    "",
    "delete from public.planning_items where lang = 'fr';",
    "delete from public.planning_items where lang = 'nl';",
    "",
    "insert into public.planning_items (lang, phase_id, type, title, description, period, status, sort_order)",
    "values",
    `${toInsertValuesSql(frRows)};`,
    "",
    "insert into public.planning_items (lang, phase_id, type, title, description, period, status, sort_order)",
    "values",
    `${toInsertValuesSql(nlRows)};`,
    "",
    "COMMIT;",
    "",
  ].join("\n");
}

async function readJson(filePath) {
  const rawContent = await readFile(filePath, "utf8");
  return JSON.parse(rawContent);
}

async function main() {
  const frLocaleJson = await readJson(FR_LOCALE_PATH);
  const nlLocaleJson = await readJson(NL_LOCALE_PATH);

  const frRows = buildLanguageRows(frLocaleJson, "fr");
  const nlRows = buildLanguageRows(nlLocaleJson, "nl");
  const sqlContent = buildSql(frRows, nlRows);

  await mkdir(OUTPUT_DIR, { recursive: true });
  await writeFile(OUTPUT_PATH, sqlContent, "utf8");

  console.log(`Generated ${path.relative(projectRoot, OUTPUT_PATH)}`);
  console.log(`Rows generated: fr=${frRows.length}, nl=${nlRows.length}`);
}

main().catch((error) => {
  const message = error instanceof Error ? error.message : String(error);
  console.error(`Failed to generate planning seed: ${message}`);
  process.exitCode = 1;
});
